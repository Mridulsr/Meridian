import { CatalogItem, Era, MovieIndustry, StreamingPlatform } from '../types/catalog';

function eraFromYear(year: number): Era {
  if (year < 1980) return '1970s';
  if (year < 1990) return '1980s';
  if (year < 2000) return '1990s';
  if (year < 2010) return '2000s';
  if (year < 2020) return '2010s';
  return '2020s';
}

interface RawMovie {
  id: string;
  title: string;
  year: number;
  creator: string;
  tags: string[];
  moods: string[];
  rating: number;
  origin: string;
  durationOrFormat: string;
  summary: string;
  whyNotable: string;
  franchise?: string;
  platforms?: StreamingPlatform[];
  industry?: MovieIndustry;
}

function inferIndustry(origin: string): MovieIndustry {
  if (origin === 'India') return 'Bollywood';
  if (origin.includes('United States') || origin.includes('UK') || origin.includes('Australia') || origin.includes('New Zealand')) {
    return 'Hollywood';
  }
  return 'International';
}

function inferPlatforms(movie: RawMovie): StreamingPlatform[] {
  if (movie.platforms && movie.platforms.length > 0) return movie.platforms;
  if (movie.year >= 2025) return ['Theaters', 'Netflix', 'Prime Video'];
  if (movie.origin === 'France' || movie.origin === 'Latvia' || movie.origin === 'Norway' || movie.origin === 'Italy' || movie.origin === 'Soviet Union' || movie.origin === 'Hong Kong') {
    return ['MUBI', 'Prime Video'];
  }
  if (movie.tags.includes('sci-fi') || movie.tags.includes('thriller')) {
    return ['Netflix', 'Prime Video'];
  }
  return ['Prime Video', 'Apple TV+'];
}

